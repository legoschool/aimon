/* ===========================================================
   AI몬스터 — 맵

   20칸 × 14줄. 한 칸이 16픽셀이므로 320×224.
   화면에 통째로 들어가므로 카메라(스크롤) 코드가 필요 없다.

   글자 하나가 한 칸
     #  나무      (막힘)
     .  땅        (걸을 수 있음)
     =  길        (걸을 수 있음)
     ~  물        (막힘)
     L  연구소    (막힘)
     C  데이터숲 · 저작권    → 복붙몬 / 슬쩍몬
     P  데이터숲 · 개인정보  → 막올림몬 / 술술몬
     D  데이터숲 · 허위정보  → 그럴싸몬 / 가짜몬
   =========================================================== */

const MAP_W = 20;
const MAP_H = 14;

const MAP = [
  "####################",
  "#....CC....##...DD.#",
  "#...CCCC...##..DDDD#",
  "#...CCCC...=...DDDD#",
  "#....CC....=....DD.#",
  "#..........=.......#",
  "#==================#",
  "#..........=.......#",
  "#....PP....=.....~~#",
  "#...PPPP...=....~~~#",
  "#...PPPP...=.....~~#",
  "#....PP....=.......#",
  "#.........LLL......#",
  "####################",
];

/* 걸어 들어갈 수 있는 칸 */
const WALKABLE = ".=CPD";

/* 조우가 일어나는 칸과 그 속성 */
const ENCOUNTER_TILE = { C: "copyright", P: "privacy", D: "disinfo" };

/* 타일을 그릴 색 (4색 그레이스케일 + 숲마다 속성색 한 방울) */
const TILE_STYLE = {
  "#": { base: "#3f4f3a", dot: "#2b381f" }, // 나무
  ".": { base: "#a8b89a", dot: "#98a98a" }, // 땅
  "=": { base: "#d8d4c0", dot: "#c9c4b0" }, // 길
  "~": { base: "#6f93b8", dot: "#5b7fa6" }, // 물
  L: { base: "#b0a898", dot: "#8a8272" }, // 연구소
  C: { base: "#7d9c7a", dot: "#3a6ea5" }, // 저작권 숲 (파랑)
  P: { base: "#7d9c7a", dot: "#c9642a" }, // 개인정보 숲 (주황)
  D: { base: "#7d9c7a", dot: "#6b4a9e" }, // 허위정보 숲 (보라)
};

/* 구역 이름 — 화면 위에 띄워준다 */
const ZONE_NAME = {
  C: "저작권 데이터숲",
  P: "개인정보 데이터숲",
  D: "허위정보 데이터숲",
  L: "AI 연구소",
  "~": "데이터 호수",
};

/* 주인공 시작 칸 (연구소 앞) */
const START = { x: 11, y: 11 };

function tileAt(x, y) {
  if (x < 0 || y < 0 || x >= MAP_W || y >= MAP_H) return "#";
  return MAP[y][x];
}

function canWalk(x, y) {
  return WALKABLE.includes(tileAt(x, y));
}
